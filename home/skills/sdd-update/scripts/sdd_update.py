"""Update the Spec Kit that sdd-init brought into the current project.

Usage:
    uv run sdd_update.py      update to the latest stable Spec Kit

The new files are generated by the official tool (specify-cli) in a temporary
directory outside the project. Files nobody changed are replaced, created or
removed; files somebody changed are left alone, and the new version is written
next to them as a comparison copy under .specify/sdd-update/<path>.new.
.specify/memory/ (the constitution) and specs/ are never touched.

The record, the hashes, the version lookup, the official tool and the required
tools all come from sdd-init's script, which is loaded from the sdd-init skill
next to this one. Nothing is loaded or run when this file is imported.
"""

from __future__ import annotations

import importlib.util
import json
import os
import re
import shutil
import sys
import tempfile
from dataclasses import dataclass, field
from pathlib import Path

# Same numbers and meanings as sdd-init.
EXIT_OK = 0
EXIT_FAILED = 1
EXIT_MISSING_TOOLS = 3
EXIT_UNAVAILABLE = 4

SKILL = "sdd-update"
USAGE = "usage: sdd_update.py"

COPIES_DIR = ".specify/sdd-update/"
COPY_SUFFIX = ".new"
PROTECTED_DIR = ".specify/memory/"
INIT_OPTIONS_PATH = ".specify/init-options.json"
REPLACE_SUFFIX = ".sdd-update-tmp"

NO_SDD_INIT = "Spec Kit was not updated: the sdd-init skill is not installed next to sdd-update. Nothing was changed."
NO_RECORD = (
    "Spec Kit was not updated: this project has no sdd-init record. "
    "Run /sdd-init first, then run /sdd-update again."
)
BAD_RECORD = "Spec Kit was not updated: .specify/sdd-init.json cannot be used. Nothing was changed."
INTERRUPTED = (
    "Spec Kit was not updated: the setup by /sdd-init was interrupted. "
    "Run /sdd-init to finish it, then run /sdd-update again."
)
GIT_TAIL = "Review the update with git status, then commit it."
GIT_NOT_A_REPO = (
    "Git: not a git repository, and none was created. Executable bits cannot be recorded "
    "until the files are added with: git add --chmod=+x .specify/scripts/bash/*.sh"
)
NEXT = (
    "Next: compare each kept file with its .new copy under .specify/sdd-update/, "
    "merge what you want, then delete the copies."
)

_NUMERIC_PREFIX = re.compile(r"\d+(\.\d+)*")


# ------------------------------------------------------------- shared code


def sdd_init_path() -> Path:
    """<this file>/../../../sdd-init/scripts/sdd_init.py, in the repository and once installed."""
    here = Path(os.path.abspath(__file__))
    return here.parents[2] / "sdd-init" / "scripts" / "sdd_init.py"


def load_sdd_init():
    """sdd-init's script as a module, or None when it is not next to this skill."""
    path = sdd_init_path()
    if not path.is_file():
        return None
    loaded = sys.modules.get("sdd_init")
    loaded_file = getattr(loaded, "__file__", None)
    if loaded_file:
        try:
            if os.path.samefile(loaded_file, path):
                return loaded
        except OSError:
            pass
    spec = importlib.util.spec_from_file_location("sdd_init", path)
    module = importlib.util.module_from_spec(spec)
    sys.modules["sdd_init"] = module
    try:
        spec.loader.exec_module(module)
    except BaseException:
        sys.modules.pop("sdd_init", None)
        raise
    return module


# ------------------------------------------------------------ small pieces


def action_line(action: str, text: str) -> str:
    """One output line, in sdd-init's format: the action padded to ten characters."""
    return f"{action:<10}{text}"


def version_numbers(version: str) -> tuple[int, ...]:
    """The leading numeric parts of a version: 1.5.0rc1 gives (1, 5, 0)."""
    match = _NUMERIC_PREFIX.match(version)
    return tuple(int(n) for n in match.group(0).split(".")) if match else ()


def compare_versions(a: str, b: str) -> int:
    """-1, 0 or 1, comparing the leading numeric parts; missing parts count as 0."""
    x, y = version_numbers(a), version_numbers(b)
    width = max(len(x), len(y))
    x, y = x + (0,) * (width - len(x)), y + (0,) * (width - len(y))
    return (x > y) - (x < y)


def decide(recorded: str, options: str | None, latest: str, status: str) -> str:
    """newer, latest, interrupted or update, checked in that order (data-model.md, Versions)."""
    if compare_versions(recorded, latest) > 0 or (options is not None and compare_versions(options, latest) > 0):
        return "newer"
    if compare_versions(recorded, latest) == 0:
        return "latest" if status == "complete" else "interrupted"
    return "update"


def newer_of(recorded: str, options: str | None) -> str:
    """The project's version: the newer of the two; a plain release wins over a preview with the same numbers."""
    if options is None:
        return recorded
    order = compare_versions(options, recorded)
    if order == 0:
        return recorded if _NUMERIC_PREFIX.fullmatch(recorded) else options
    return options if order > 0 else recorded


def copy_path(path: str) -> str:
    """Where the comparison copy of path goes."""
    return f"{COPIES_DIR}{path}{COPY_SUFFIX}"


def copy_target(path: str) -> str | None:
    """The project path a comparison copy belongs to, or None when path is not a copy."""
    if not path.startswith(COPIES_DIR) or not path.endswith(COPY_SUFFIX):
        return None
    target = path[len(COPIES_DIR) : -len(COPY_SUFFIX)]
    return target or None


def is_protected(path: str) -> bool:
    """.specify/memory/ is never created, replaced, removed or reported."""
    return path.startswith(PROTECTED_DIR)


def read_options_version(root: Path) -> str | None:
    """speckit_version from .specify/init-options.json, or None when it cannot be read."""
    try:
        data = json.loads((root / INIT_OPTIONS_PATH).read_bytes().decode("utf-8"))
    except (OSError, ValueError):
        return None
    version = data.get("speckit_version") if isinstance(data, dict) else None
    return version if isinstance(version, str) else None


# --------------------------------------------------------------- the plan


@dataclass
class Plan:
    """What the update will do, decided before anything is written. Read only."""

    create: list[str] = field(default_factory=list)
    same: list[str] = field(default_factory=list)
    update: list[str] = field(default_factory=list)
    keep: dict[str, str] = field(default_factory=dict)  # path -> the text in brackets
    orphans: list[str] = field(default_factory=list)  # kept files the new version no longer provides
    remove: list[str] = field(default_factory=list)
    forget: list[str] = field(default_factory=list)
    copies: dict[str, str] = field(default_factory=dict)  # copy path -> project path
    sources: dict[str, Path] = field(default_factory=dict)  # project path -> file with the new content
    new_hashes: dict[str, str] = field(default_factory=dict)
    origins: dict[str, str] = field(default_factory=dict)
    blocked: list[str] = field(default_factory=list)


def current_hash(S, root: Path, path: str) -> str | None:
    """Hash of the project file, or None when it is not a regular file (that differs from every hash)."""
    target = root / path
    if target.is_symlink() or not target.is_file():
        return None
    return S.content_hash(target.read_bytes())


def make_plan(S, root: Path, record, version: str, sources: dict, origins: dict) -> Plan:
    plan = Plan(sources=dict(sources), origins=dict(origins))
    recorded = {e.path: e for e in record.entries}
    speckit_recorded = {e.path for e in record.entries if e.origin == "speckit"}

    for path in sorted((set(sources) | speckit_recorded)):
        if is_protected(path):
            continue
        exists = os.path.lexists(root / path)
        cur = current_hash(S, root, path) if exists else None
        rec = recorded[path].sha256 if path in recorded else None
        if path in sources:
            new = S.content_hash(sources[path].read_bytes())
            plan.new_hashes[path] = new
            if not exists:
                plan.create.append(path)
            elif cur == new:
                plan.same.append(path)
            elif rec is not None and cur == rec:
                plan.update.append(path)
            else:
                copy = copy_path(path)
                plan.copies[copy] = path
                why = "modified" if rec is not None else "not created by sdd-init"
                plan.keep[path] = f"{why}; new version: {copy}"
        else:
            if not exists:
                plan.forget.append(path)
            elif cur == rec:
                plan.remove.append(path)
            else:
                plan.keep[path] = f"modified; no longer part of Spec Kit {version}"
                plan.orphans.append(path)

    # Anything in the way of a file to create or a copy to write stops the update here.
    old_copies = {e.path for e in record.entries if e.origin == "sdd-update"}
    blocked = set()
    for path in plan.create + list(plan.copies) + [S.RECORD_PATH]:
        parent = S._blocked_parent(root, path)
        if parent:
            blocked.add(parent)
    for copy in plan.copies:
        target = root / copy
        if os.path.lexists(target) and (copy not in old_copies or target.is_symlink() or not target.is_file()):
            blocked.add(copy)
    plan.blocked = sorted(blocked)
    return plan


# ----------------------------------------------------------------- update


def cmd_update(S, resolve_version, run_official) -> int:
    missing = S.missing_tools()
    if missing:
        S.report_missing_tools(missing, SKILL, "changed")
        return EXIT_MISSING_TOOLS

    root = S.find_project_root(Path.cwd())
    try:
        record = S.load_record(root)
    except S.InvalidRecord as exc:
        print(BAD_RECORD)
        S.report_invalid_record(exc, SKILL)
        return EXIT_FAILED
    if record is None:
        print(NO_RECORD)
        S.error(
            f"error: {S.RECORD_PATH} does not exist, so no file can be proven to be created by sdd-init.",
            "Run /sdd-init first; it keeps every existing file. Then run /sdd-update again.",
        )
        return EXIT_FAILED

    staging = Path(tempfile.mkdtemp(prefix="sdd-update-"))
    try:
        try:
            latest = resolve_version()
        except Exception as exc:
            S.report_unavailable(exc, SKILL, "changed")
            return EXIT_UNAVAILABLE

        options = read_options_version(root)
        decision = decide(record.speckit_version, options, latest, record.status)
        if decision == "newer":
            print(
                f"Spec Kit {newer_of(record.speckit_version, options)} is newer than the latest stable release "
                f"{latest}. Nothing changed."
            )
            return EXIT_OK
        if decision == "latest":
            return report_pending(S, root, record)
        if decision == "interrupted":
            print(INTERRUPTED)
            S.error(
                f"error: {S.RECORD_PATH} says the setup of Spec Kit {record.speckit_version} did not finish.",
                "Nothing was changed. Run /sdd-init to finish it, then run /sdd-update again.",
            )
            return EXIT_FAILED

        try:
            out_dir = staging / "out"
            out_dir.mkdir()
            run_official(latest, out_dir)
            S._check_generated_version(out_dir, latest)
            if os.path.lexists(out_dir / S.RECORD_PATH):
                raise S.StepFailed(f"the official tool produced {S.RECORD_PATH}, which belongs to sdd-init")
            generated = S._generated_files(out_dir)
            for path in generated:
                if path.startswith(COPIES_DIR):
                    raise S.StepFailed(f"the official tool produced {path}, which is where sdd-update keeps its copies")
        except Exception as exc:
            S.report_unavailable(exc, SKILL, "changed")
            return EXIT_UNAVAILABLE

        sources = {path: out_dir / path for path in generated}
        origins = {path: "speckit" for path in generated}
        if S.GITATTRIBUTES_PATH not in sources and not os.path.lexists(root / S.GITATTRIBUTES_PATH):
            sources[S.GITATTRIBUTES_PATH] = S.write_own_gitattributes(staging)
            origins[S.GITATTRIBUTES_PATH] = "sdd-init"

        plan = make_plan(S, root, record, latest, sources, origins)
        if plan.blocked:
            first = plan.blocked[0]
            print(f"Spec Kit was not updated: {first} is in the way. Nothing was changed. Move it away and run /sdd-update again.")
            S.error(
                f"error: {first} is in the way of a file sdd-update has to write.",
                "Nothing was changed. Move it away, then run /sdd-update again.",
            )
            return EXIT_FAILED

        return apply_update(S, root, record, latest, plan, [p for p in generated if p.endswith(".sh")])
    finally:
        shutil.rmtree(staging, ignore_errors=True)


def report_pending(S, root: Path, record) -> int:
    """Already the latest stable release: list kept files that still differ from their copy. Read only."""
    lines = []
    for entry in record.entries:
        if entry.origin != "sdd-update":
            continue
        target = copy_target(entry.path)
        copy = root / entry.path
        if target is None or copy.is_symlink() or not copy.is_file() or not os.path.lexists(root / target):
            continue
        if current_hash(S, root, target) != S.content_hash(copy.read_bytes()):
            lines.append(
                (target, action_line("kept", f"{target} (still differs from Spec Kit {record.speckit_version}; "
                                             f"new version: {entry.path})"))
            )  # fmt: skip
    for _target, text in sorted(lines):
        print(text)
    print(f"Spec Kit {record.speckit_version} is already the latest stable release. Nothing changed.")
    if lines:
        print(NEXT)
    return EXIT_OK


def replace_file(source: Path, target: Path) -> None:
    """Write the new content next to target, give it source's mode, then swap it in."""
    temporary = target.with_name(target.name + REPLACE_SUFFIX)
    with open(temporary, "wb") as handle:
        handle.write(source.read_bytes())
    shutil.copymode(source, temporary)
    os.replace(temporary, target)


def remove_file(target: Path) -> None:
    target.unlink()


def write_copy(source: Path, target: Path) -> None:
    """A comparison copy: the new bytes as a plain file. Fails when target already exists."""
    data = source.read_bytes()
    with open(target, "xb") as handle:
        handle.write(data)


def apply_update(S, root: Path, record, version: str, plan: Plan, new_scripts: list[str]) -> int:
    in_git = S.is_git_work_tree(root)
    recorded = {e.path: e for e in record.entries}
    old_copies = sorted(e.path for e in record.entries if e.origin == "sdd-update")

    # Files that exist before the update and are left in place by it.
    leaving = set(plan.remove) | set(plan.forget) | set(plan.orphans)
    pending = S.unstaged_scripts(root, [e for e in record.entries if e.path not in leaving]) if in_git else []

    new_dirs = set(record.created_dirs)
    for path in plan.create + list(plan.copies):
        new_dirs.update(S._missing_dirs(root, path))

    # The applying record: what is there plus what is about to be created; the version is still the old one.
    applying = {path: S.Entry(e.path, e.sha256, e.origin, e.staged_executable) for path, e in recorded.items()}
    for path in plan.create:
        applying[path] = S.Entry(path, plan.new_hashes[path], plan.origins[path], False)
    for copy, path in plan.copies.items():
        applying[copy] = S.Entry(copy, plan.new_hashes[path], "sdd-update", False)

    # The final record: every hash is what the new version provides at that path.
    final = {
        path: S.Entry(e.path, e.sha256, e.origin, e.staged_executable)
        for path, e in applying.items()
        if e.origin != "sdd-update" or e.path in plan.copies
    }
    for path in plan.same + plan.update + list(plan.copies.values()):
        if path in final:
            final[path].sha256 = plan.new_hashes[path]
    for path in plan.remove + plan.forget + plan.orphans:
        final.pop(path, None)

    result = S.Record("applying", record.speckit_version, list(applying.values()), sorted(new_dirs))
    staged, removed_dirs = [], set()
    try:
        S.write_record(root, result)
        for copy in old_copies:
            target = root / copy
            if target.is_symlink() or target.is_file():
                target.unlink()
        for copy, path in sorted(plan.copies.items()):
            (root / copy).parent.mkdir(parents=True, exist_ok=True)
            write_copy(plan.sources[path], root / copy)
        for path in plan.create:
            (root / path).parent.mkdir(parents=True, exist_ok=True)
            S.copy_new_file(plan.sources[path], root / path)
        for path in plan.update:
            replace_file(plan.sources[path], root / path)
        for path in plan.remove:
            remove_file(root / path)
        for directory in sorted(new_dirs, key=lambda d: (-d.count("/"), d)):
            target = root / directory
            if target.is_dir() and not target.is_symlink() and not any(target.iterdir()):
                os.rmdir(target)
                removed_dirs.add(directory)
        if in_git:
            unstage_removed(S, root, [recorded[p] for p in plan.remove])
            to_stage = sorted(set(pending) | {p for p in plan.create if p.endswith(".sh")})
            staged = S.stage_executable(root, to_stage, final)
        result = S.Record("complete", version, list(final.values()), sorted(new_dirs - removed_dirs))
        S.write_record(root, result)
    except OSError as exc:
        S.error(f"error: writing into the project failed: {exc}", (
            "Some files may already have been updated. Fix the cause, then run /sdd-update again; "
            "it finishes the update and never overwrites a file you changed."
        ))  # fmt: skip
        return EXIT_FAILED

    warnings = S.scripts_without_lf_eol(root, new_scripts) if in_git else []

    for path in plan.update:
        print(action_line("updated", path))
    for path in plan.create:
        print(action_line("created", path))
    for path in plan.remove:
        print(action_line("removed", path))
    for path in sorted(plan.keep):
        print(action_line("kept", f"{path} ({plan.keep[path]})"))
    for path in staged:
        print(action_line("staged", f"{path} (executable bit recorded in the git index)"))
    for path in warnings:
        print(action_line(
            "warning",
            f"{path} has no eol=lf rule in git; it will not run after a checkout that converts line endings",
        ))  # fmt: skip
    print(
        f"Spec Kit updated from {record.speckit_version} to {version}: {len(plan.update)} updated, "
        f"{len(plan.create)} created, {len(plan.remove)} removed, {len(plan.keep)} kept."
    )
    if not in_git:
        print(GIT_NOT_A_REPO)
    elif staged:
        print(f"Git: {len(staged)} files were added to the index and nothing was committed. {GIT_TAIL}")
    else:
        print(f"Git: nothing was added to the index and nothing was committed. {GIT_TAIL}")
    if plan.copies:
        print(NEXT)
    return EXIT_OK


def unstage_removed(S, root: Path, removed) -> None:
    """Take removed .sh that sdd-init or sdd-update staged and nobody committed back out of the index."""
    candidates = [e.path for e in removed if e.staged_executable]
    if not candidates:
        return
    in_index, in_head = S.index_paths(root), S.head_paths(root)
    for path in candidates:
        if path in in_index and path not in in_head:
            S.git(root, "rm", "--cached", "--quiet", "--", path)


# -------------------------------------------------------------------- main


def main(argv=None, *, resolve_version=None, run_official=None) -> int:
    """Entry point. The two keyword arguments exist only so tests can replace those steps."""
    args = list(sys.argv[1:] if argv is None else argv)
    if args:
        print(USAGE, file=sys.stderr)
        print("sdd-update takes no arguments: it always updates to the latest stable release.", file=sys.stderr)
        return EXIT_FAILED
    S = load_sdd_init()
    if S is None:
        print(NO_SDD_INIT)
        print(
            f"error: {sdd_init_path().as_posix()} was not found. sdd-update uses the sdd-init skill's script; "
            "install both skills together.",
            file=sys.stderr,
        )
        return EXIT_FAILED
    return cmd_update(
        S,
        resolve_version or S.fetch_latest_version,
        run_official or S.run_official_tool,
    )


if __name__ == "__main__":
    # Same bytes on both platforms: UTF-8 and LF, whatever the console default is.
    for stream in (sys.stdout, sys.stderr):
        stream.reconfigure(encoding="utf-8", newline="\n")
    sys.exit(main())
