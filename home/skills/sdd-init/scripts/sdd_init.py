"""Bring Spec Kit into the current project, or remove it again.

Usage:
    uv run sdd_init.py init      bring in the latest stable Spec Kit
    uv run sdd_init.py remove    remove what init created and nobody changed

Spec Kit's files are always generated by the official tool (specify-cli) in a
temporary directory outside the project and copied byte for byte to places
that do not exist yet. Existing files are never overwritten or modified.
"""

