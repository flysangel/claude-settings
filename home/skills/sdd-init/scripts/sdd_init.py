"""Bring Spec Kit into the current project, or remove it again.

Usage:
    uv run sdd_init.py init      bring in the latest stable Spec Kit
    uv run sdd_init.py remove    remove what init created and nobody changed

Spec Kit's files are always generated by the official tool (specify-cli) in a
temporary directory outside the project and copied byte for byte to places
that do not exist yet. Existing files are never overwritten or modified.
"""

from __future__ import annotations

import hashlib
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
import urllib.request
from dataclasses import dataclass, field
from pathlib import Path

EXIT_OK = 0
EXIT_FAILED = 1
EXIT_MISSING_TOOLS = 3
EXIT_UNAVAILABLE = 4

USAGE = "usage: sdd_init.py {init|remove}"

REQUIRED_TOOLS = ("bash", "git", "uv")
PYPI_URL = "https://pypi.org/pypi/specify-cli/json"
PACKAGE = "specify-cli"
INIT_OPTIONS = {"integration": "claude", "script": "sh"}

RECORD_PATH = ".specify/sdd-init.json"
SCHEMA = 1
GITATTRIBUTES_PATH = ".specify/.gitattributes"
GITATTRIBUTES_RULE = "scripts/bash/*.sh text eol=lf"

NEXT_STEPS = (
    "Next: run /sdd-grill to be questioned until the constitution and specs are decided.",
    "Or use Spec Kit directly: run /speckit-constitution, then /speckit-specify.",
)
NOTHING_TO_REMOVE = (
    "Nothing to remove: this project has no sdd-init record, "
    "so no file can be proven to be created by sdd-init."
)
NOTHING_REMOVED = (
    "Nothing was removed: .specify/sdd-init.json cannot be read, "
    "so no file can be proven to be created by sdd-init."
)

_STABLE_VERSION = re.compile(r"\d+(\.\d+)*")
_SHA256 = re.compile(r"[0-9a-f]{64}")


class StepFailed(Exception):
    """Getting the version or running the official tool failed (exit code 4)."""

    def __init__(self, reason: str, detail: str = ""):
        super().__init__(reason)
        self.reason = reason
        self.detail = detail


class InvalidRecord(Exception):
    """The record exists but cannot be trusted.

    kind is "unreadable" (not parseable, unknown schema, wrong shape) or
    "paths" (it names a path outside the places sdd-init writes to).
    """

    def __init__(self, kind: str, reason: str):
        super().__init__(reason)
        self.kind = kind
        self.reason = reason


# ------------------------------------------------------------------ output


def emit(action: str, text: str) -> None:
    print(f"{action:<10}{text}")


def error(*lines: str) -> None:
    for text in lines:
        if text:
            print(text, file=sys.stderr)


# ------------------------------------------------------- project root, git


def find_tool(name: str) -> str | None:
    return shutil.which(name)


def git(cwd: Path, *args: str) -> subprocess.CompletedProcess | None:
    """Run git and return the result, or None when git cannot be started."""
    try:
        return subprocess.run(
            ["git", "-c", "core.quotePath=false", *args],
            cwd=cwd,
            stdin=subprocess.DEVNULL,
            capture_output=True,
        )
    except OSError:
        return None


def _text(data: bytes) -> str:
    return data.decode("utf-8", errors="replace")


def find_project_root(cwd: Path) -> Path:
    """The top of the git work tree that contains cwd, otherwise cwd itself."""
    done = git(cwd, "rev-parse", "--show-toplevel")
    if done is not None and done.returncode == 0:
        top = _text(done.stdout).strip()
        if top:
            return Path(top)
    return Path(cwd)


def is_git_work_tree(root: Path) -> bool:
    done = git(root, "rev-parse", "--is-inside-work-tree")
    return done is not None and done.returncode == 0 and _text(done.stdout).strip() == "true"


def _listed_paths(root: Path, *args: str) -> set[str]:
    done = git(root, *args)
    if done is None or done.returncode != 0:
        return set()
    return {p for p in _text(done.stdout).split("\0") if p}


def head_paths(root: Path) -> set[str]:
    """Paths in HEAD; empty when there is no commit yet."""
    return _listed_paths(root, "ls-tree", "-r", "-z", "--name-only", "HEAD")


def index_paths(root: Path) -> set[str]:
    return _listed_paths(root, "ls-files", "-z")


def effective_eol(root: Path, path: str) -> str | None:
    done = git(root, "check-attr", "-z", "eol", "--", path)
    if done is None or done.returncode != 0:
        return None
    fields = _text(done.stdout).split("\0")
    return fields[2] if len(fields) >= 3 else None


# ------------------------------------------------------------ content hash


def content_hash(data: bytes) -> str:
    """SHA-256 of the content with every CRLF replaced by LF."""
    return hashlib.sha256(data.replace(b"\r\n", b"\n")).hexdigest()


# ------------------------------------------------------------------ record


@dataclass
class Entry:
    path: str
    sha256: str
    origin: str
    staged_executable: bool = False


@dataclass
class Record:
    status: str
    speckit_version: str
    entries: list[Entry] = field(default_factory=list)
    created_dirs: list[str] = field(default_factory=list)


def _clean_segments(path: object) -> list[str] | None:
    if not isinstance(path, str) or not path:
        return None
    if "\\" in path or ":" in path or path.startswith("/"):
        return None
    parts = path.split("/")
    if any(part in ("", ".", "..") for part in parts):
        return None
    return parts


def _is_speckit_skill(name: str) -> bool:
    return name.startswith("speckit-") and len(name) > len("speckit-")


def is_recordable_path(path: object) -> bool:
    """True for files under .specify/ or .claude/skills/speckit-*/, except the record."""
    parts = _clean_segments(path)
    if parts is None or path == RECORD_PATH:
        return False
    if parts[0] == ".specify":
        return len(parts) >= 2
    return len(parts) >= 4 and parts[:2] == [".claude", "skills"] and _is_speckit_skill(parts[2])


def is_recordable_dir(path: object) -> bool:
    parts = _clean_segments(path)
    if parts is None:
        return False
    if parts[0] == ".specify":
        return True
    if parts in ([".claude"], [".claude", "skills"]):
        return True
    return len(parts) >= 3 and parts[:2] == [".claude", "skills"] and _is_speckit_skill(parts[2])


def serialize_record(record: Record) -> bytes:
    data = {
        "schema": SCHEMA,
        "status": record.status,
        "speckit_version": record.speckit_version,
        "init_options": dict(INIT_OPTIONS),
        "entries": [
            {
                "path": e.path,
                "sha256": e.sha256,
                "origin": e.origin,
                "staged_executable": bool(e.staged_executable),
            }
            for e in sorted(record.entries, key=lambda e: e.path)
        ],
        "created_dirs": sorted(set(record.created_dirs)),
    }
    return (json.dumps(data, indent=2, ensure_ascii=False) + "\n").encode("utf-8")


def write_record(root: Path, record: Record) -> None:
    target = root / RECORD_PATH
    target.parent.mkdir(parents=True, exist_ok=True)
    temporary = target.with_name(target.name + ".tmp")
    temporary.write_bytes(serialize_record(record))
    os.replace(temporary, target)


def load_record(root: Path) -> Record | None:
    """Return the record, None when there is none, or raise InvalidRecord."""
    target = root / RECORD_PATH
    if not os.path.lexists(target):
        return None

    def unreadable(reason: str) -> InvalidRecord:
        return InvalidRecord("unreadable", reason)

    try:
        data = json.loads(target.read_bytes().decode("utf-8"))
    except (OSError, ValueError) as exc:
        raise unreadable(f"it cannot be parsed: {exc}") from exc
    if not isinstance(data, dict):
        raise unreadable("it is not a JSON object")
    schema = data.get("schema")
    if isinstance(schema, bool) or schema != SCHEMA:
        raise unreadable(f"its schema is {schema!r}, and this version only knows schema {SCHEMA}")
    if data.get("status") not in ("applying", "complete"):
        raise unreadable("its status is neither applying nor complete")
    version = data.get("speckit_version")
    if not isinstance(version, str) or not _STABLE_VERSION.fullmatch(version):
        raise unreadable("its speckit_version is not a stable version number")
    if data.get("init_options") != INIT_OPTIONS:
        raise unreadable("its init_options are not the ones sdd-init uses")
    raw_entries = data.get("entries")
    raw_dirs = data.get("created_dirs")
    if not isinstance(raw_entries, list) or not isinstance(raw_dirs, list):
        raise unreadable("entries or created_dirs is not a list")

    entries: list[Entry] = []
    for raw in raw_entries:
        if not isinstance(raw, dict) or not isinstance(raw.get("path"), str):
            raise unreadable("an entry has no path")
        sha = raw.get("sha256")
        if not isinstance(sha, str) or not _SHA256.fullmatch(sha):
            raise unreadable(f"the entry for {raw['path']} has no valid sha256")
        if raw.get("origin") not in ("speckit", "sdd-init"):
            raise unreadable(f"the entry for {raw['path']} has an unknown origin")
        if not isinstance(raw.get("staged_executable"), bool):
            raise unreadable(f"the entry for {raw['path']} has no staged_executable flag")
        entries.append(Entry(raw["path"], sha, raw["origin"], raw["staged_executable"]))
    if any(not isinstance(d, str) for d in raw_dirs):
        raise unreadable("created_dirs holds something that is not a path")
    if len({e.path for e in entries}) != len(entries):
        raise unreadable("a path is listed twice")

    for entry in entries:
        if not is_recordable_path(entry.path):
            raise InvalidRecord(
                "paths", f"it lists {entry.path!r}, which is outside .specify/ and .claude/skills/speckit-*/"
            )
    for directory in raw_dirs:
        if not is_recordable_dir(directory):
            raise InvalidRecord(
                "paths", f"it lists the directory {directory!r}, which is outside .specify/ and .claude/skills/"
            )

    return Record(
        status=data["status"],
        speckit_version=version,
        entries=sorted(entries, key=lambda e: e.path),
        created_dirs=sorted(set(raw_dirs)),
    )


# ----------------------------------------------------------------- version


def pick_latest_stable(releases: dict) -> str | None:
    """The largest version that is plain N(.N)* and has a file that is not yanked."""
    candidates = []
    for version, files in releases.items():
        if not isinstance(version, str) or not _STABLE_VERSION.fullmatch(version):
            continue
        if not isinstance(files, list):
            continue
        if not any(isinstance(f, dict) and not f.get("yanked", False) for f in files):
            continue
        candidates.append((tuple(int(n) for n in version.split(".")), version))
    return max(candidates)[1] if candidates else None


def fetch_latest_version() -> str:
    """Ask PyPI for the latest stable specify-cli. One attempt, no fallback."""
    request = urllib.request.Request(PYPI_URL, headers={"Accept": "application/json", "User-Agent": "sdd-init"})
    try:
        with urllib.request.urlopen(request, timeout=30) as response:
            data = json.loads(response.read().decode("utf-8"))
        releases = data["releases"]
        if not isinstance(releases, dict):
            raise ValueError("unexpected response")
    except Exception as exc:  # network, HTTP, timeout, or an unexpected body
        raise StepFailed(f"{PYPI_URL} could not be read ({_one_line(str(exc)) or type(exc).__name__})") from exc
    version = pick_latest_stable(releases)
    if version is None:
        raise StepFailed(f"PyPI lists no stable release of {PACKAGE}")
    return version


def run_official_tool(version: str, dest: Path) -> None:
    """Generate Spec Kit's files into the empty directory dest with the official tool."""
    command = [
        "uv", "tool", "run", "--from", f"{PACKAGE}=={version}",
        "specify", "init", "--here", "--non-interactive", "--ignore-agent-tools",
        "--integration", INIT_OPTIONS["integration"], "--script", INIT_OPTIONS["script"],
    ]  # fmt: skip
    env = dict(os.environ)
    # The official tool prints non-ASCII characters; keep that from failing on a piped Windows console.
    env["PYTHONIOENCODING"] = "utf-8"
    env["PYTHONUTF8"] = "1"
    try:
        done = subprocess.run(
            command,
            cwd=dest,
            env=env,
            stdin=subprocess.DEVNULL,
            stdout=subprocess.PIPE,
            stderr=subprocess.STDOUT,
            timeout=600,
        )
    except subprocess.TimeoutExpired as exc:
        raise StepFailed(f"the official tool ({PACKAGE} {version}) did not finish in time") from exc
    except OSError as exc:
        raise StepFailed(f"uv could not be started ({_one_line(str(exc))})") from exc
    if done.returncode != 0:
        tail = "\n".join(_text(done.stdout).strip().splitlines()[-15:])
        raise StepFailed(
            f"uv could not run the official tool ({PACKAGE} {version}), exit code {done.returncode}",
            detail=tail,
        )


def _one_line(text: str) -> str:
    return " ".join(text.split()).rstrip(".")


def _check_generated_version(out_dir: Path, version: str) -> None:
    options = out_dir / ".specify" / "init-options.json"
    try:
        found = json.loads(options.read_bytes().decode("utf-8")).get("speckit_version")
    except (OSError, ValueError, AttributeError) as exc:
        raise StepFailed(
            "the official tool did not produce a readable .specify/init-options.json"
        ) from exc
    if found != version:
        raise StepFailed(f"the official tool reported version {found}, but {version} was requested")


def _generated_files(out_dir: Path) -> list[str]:
    paths = []
    for current, _dirs, files in os.walk(out_dir):
        for name in files:
            paths.append((Path(current) / name).relative_to(out_dir).as_posix())
    for path in paths:
        if not is_recordable_path(path):
            raise StepFailed(
                f"the official tool produced {path}, which is outside .specify/ and .claude/skills/speckit-*/"
            )
    return sorted(paths)


# -------------------------------------------------------------------- init


def copy_new_file(source: Path, target: Path) -> None:
    """Copy source to target byte for byte. Fails when target already exists."""
    data = source.read_bytes()
    with open(target, "xb") as handle:
        handle.write(data)
    shutil.copymode(source, target)


def _missing_dirs(root: Path, path: str) -> list[str]:
    """Ancestors of path (relative to root) that do not exist yet."""
    parts = path.split("/")[:-1]
    result = []
    for depth in range(1, len(parts) + 1):
        relative = "/".join(parts[:depth])
        if not os.path.lexists(root / relative):
            result.append(relative)
    return result


def _blocked_parent(root: Path, path: str) -> str | None:
    """An ancestor of path that exists but is not a directory."""
    parts = path.split("/")[:-1]
    for depth in range(1, len(parts) + 1):
        relative = "/".join(parts[:depth])
        candidate = root / relative
        if os.path.lexists(candidate) and not candidate.is_dir():
            return relative
    return None


def cmd_init(resolve_version, run_official) -> int:
    missing = sorted(name for name in REQUIRED_TOOLS if find_tool(name) is None)
    if missing:
        for name in missing:
            emit("missing", name)
        print("Missing required tools. Nothing was created. Install them and run /sdd-init again.")
        error(
            f"error: required tools are missing: {', '.join(missing)}",
            "Install them, make sure they are on PATH, then run /sdd-init again. "
            "On Windows, bash is Git Bash, which comes with Git for Windows.",
        )
        return EXIT_MISSING_TOOLS

    root = find_project_root(Path.cwd())
    try:
        record = load_record(root)
    except InvalidRecord as exc:
        error(
            f"error: {RECORD_PATH} is not a record this version of sdd-init can use: {exc.reason}.",
            "Nothing was changed. The file may belong to another tool or a newer sdd-init; "
            "move it away or restore it, then run /sdd-init again.",
        )
        return EXIT_FAILED

    if record and record.status == "complete" and all((root / e.path).is_file() for e in record.entries):
        print(f"Spec Kit {record.speckit_version} is already initialized. Nothing changed.")
        return EXIT_OK

    staging = Path(tempfile.mkdtemp(prefix="sdd-init-"))
    try:
        try:
            # A partly applied project is finished with the version it started with.
            version = record.speckit_version if record else resolve_version()
            out_dir = staging / "out"
            out_dir.mkdir()
            run_official(version, out_dir)
            _check_generated_version(out_dir, version)
            generated = _generated_files(out_dir)
        except Exception as exc:
            reason = _one_line(exc.reason if isinstance(exc, StepFailed) else str(exc)) or type(exc).__name__
            print(
                f"Could not get the latest stable Spec Kit release: {reason}. Nothing was created. "
                "Check the network connection and run /sdd-init again."
            )
            error(
                f"error: {reason}",
                getattr(exc, "detail", ""),
                "Nothing was created. Check the network connection and that uv can download "
                f"{PACKAGE} from PyPI, then run /sdd-init again. "
                "sdd-init does not retry and does not install Spec Kit any other way.",
            )
            return EXIT_UNAVAILABLE

        sources = {path: out_dir / path for path in generated}
        origins = {path: "speckit" for path in generated}
        if GITATTRIBUTES_PATH not in sources:
            own = staging / "own" / "gitattributes"
            own.parent.mkdir()
            own.write_bytes((GITATTRIBUTES_RULE + "\n").encode("utf-8"))
            sources[GITATTRIBUTES_PATH] = own
            origins[GITATTRIBUTES_PATH] = "sdd-init"

        return _apply_init(root, record, version, sources, origins)
    finally:
        shutil.rmtree(staging, ignore_errors=True)


def _apply_init(root: Path, record: Record | None, version: str, sources: dict, origins: dict) -> int:
    in_git = is_git_work_tree(root)
    recorded = {e.path: e for e in record.entries} if record else {}

    # ---- plan: read only
    create, skip = [], []
    for path in sorted(sources):
        if not os.path.lexists(root / path):
            create.append(path)
        elif path not in recorded:
            skip.append(path)
    for path in create + [RECORD_PATH]:
        blocked = _blocked_parent(root, path)
        if blocked:
            error(
                f"error: {blocked} exists and is not a directory, so {path} cannot be created.",
                "Nothing was changed. Move it away, then run /sdd-init again.",
            )
            return EXIT_FAILED

    warn = False
    if GITATTRIBUTES_PATH in skip and origins[GITATTRIBUTES_PATH] == "sdd-init":
        scripts = [p for p in sources if p.endswith(".sh")] or [".specify/scripts/bash/check.sh"]
        warn = not in_git or any(effective_eol(root, p) != "lf" for p in scripts)

    entries = {path: entry for path, entry in recorded.items() if os.path.lexists(root / path)}
    for path in create:
        entries[path] = Entry(path, content_hash(sources[path].read_bytes()), origins[path], False)
    new_dirs: set[str] = set(record.created_dirs) if record else set()
    for path in create + [RECORD_PATH]:
        new_dirs.update(_missing_dirs(root, path))

    result = Record("applying", version, list(entries.values()), sorted(new_dirs))

    # ---- apply
    staged = []
    try:
        write_record(root, result)
        for path in create:
            target = root / path
            target.parent.mkdir(parents=True, exist_ok=True)
            copy_new_file(sources[path], target)
        if in_git:
            for path in create:
                if not path.endswith(".sh"):
                    continue
                done = git(root, "add", "--chmod=+x", "--", path)
                if done is not None and done.returncode == 0:
                    entries[path].staged_executable = True
                    staged.append(path)
                else:
                    message = _one_line(_text(done.stderr)) if done is not None else "git could not be started"
                    error(f"note: {path} was not added to the git index: {message}")
        result.status = "complete"
        write_record(root, result)
    except OSError as exc:
        error(
            f"error: writing into the project failed: {exc}",
            "Some files may already have been created. Fix the cause, then run /sdd-init again; "
            "it creates what is still missing and overwrites nothing.",
        )
        return EXIT_FAILED

    # ---- report
    for path in create:
        emit("created", path)
    for path in skip:
        emit("skipped", f"{path} (already exists, left untouched)")
    for path in staged:
        emit("staged", f"{path} (executable bit recorded in the git index)")
    if warn:
        emit(
            "warning",
            f"{GITATTRIBUTES_PATH} was not created by sdd-init; add this line to it: {GITATTRIBUTES_RULE}",
        )
    print(f"Spec Kit {version} initialized: {len(create)} created, {len(skip)} skipped.")
    if not in_git:
        print(
            "Git: not a git repository, and none was created. Executable bits cannot be recorded "
            "until the files are added with: git add --chmod=+x .specify/scripts/bash/*.sh"
        )
    else:
        committed = head_paths(root)
        uncommitted = sum(1 for path in entries if path not in committed)
        if staged:
            print(
                f"Git: {len(staged)} files were added to the index and nothing was committed. "
                f"{uncommitted} paths are uncommitted."
            )
        else:
            print(f"Git: nothing was added to the index. {uncommitted} paths are uncommitted.")
    for text in NEXT_STEPS:
        print(text)
    return EXIT_OK


# ------------------------------------------------------------------ remove


def cmd_remove() -> int:
    root = find_project_root(Path.cwd())
    try:
        record = load_record(root)
    except InvalidRecord as exc:
        print(NOTHING_REMOVED)
        error(f"{RECORD_PATH} is not a record this version of sdd-init can use: {exc.reason}.")
        if exc.kind == "paths":
            error("error: sdd-init only removes files under .specify/ and .claude/skills/speckit-*/, so it refused.")
            return EXIT_FAILED
        return EXIT_OK
    if record is None:
        print(NOTHING_TO_REMOVE)
        return EXIT_OK

    in_git = is_git_work_tree(root)
    deleted, kept, unstaged = [], [], []
    try:
        for entry in record.entries:
            target = root / entry.path
            if not os.path.lexists(target):
                continue
            if not target.is_file() or target.is_symlink() or content_hash(target.read_bytes()) != entry.sha256:
                kept.append(entry.path)
                continue
            target.unlink()
            deleted.append(entry.path)

        if in_git:
            candidates = [e.path for e in record.entries if e.staged_executable and e.path in deleted]
            if candidates:
                in_index, in_head = index_paths(root), head_paths(root)
                for path in candidates:
                    if path in in_index and path not in in_head:
                        done = git(root, "rm", "--cached", "--quiet", "--", path)
                        if done is not None and done.returncode == 0:
                            unstaged.append(path)

        (root / RECORD_PATH).unlink()
        for directory in sorted(record.created_dirs, key=lambda d: (-d.count("/"), d)):
            try:
                os.rmdir(root / directory)
            except OSError:
                pass  # not empty, or already gone: it stays
    except OSError as exc:
        error(
            f"error: removing failed: {exc}",
            "Some files may already have been deleted. Fix the cause, then run /sdd-init remove again.",
        )
        return EXIT_FAILED

    for path in deleted:
        emit("deleted", path)
    for path in kept:
        emit("kept", f"{path} (modified since init)")
    for path in unstaged:
        emit("unstaged", path)
    print(f"Spec Kit removed: {len(deleted)} deleted, {len(kept)} kept because they were modified.")
    return EXIT_OK


# -------------------------------------------------------------------- main


def main(argv=None, *, resolve_version=fetch_latest_version, run_official=run_official_tool) -> int:
    """Entry point. The two keyword arguments exist only so tests can replace those steps."""
    args = list(sys.argv[1:] if argv is None else argv)
    if len(args) != 1 or args[0] not in ("init", "remove"):
        print(USAGE, file=sys.stderr)
        return EXIT_FAILED
    if args[0] == "init":
        return cmd_init(resolve_version, run_official)
    return cmd_remove()


if __name__ == "__main__":
    # Same bytes on both platforms: UTF-8 and LF, whatever the console default is.
    for stream in (sys.stdout, sys.stderr):
        stream.reconfigure(encoding="utf-8", newline="\n")
    sys.exit(main())
